import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {Buffer} from 'node:buffer';
import {validateAssetPolicy,preparePngSource} from '../../scripts/lean/native/asset-policy.mjs';

async function sourcedAsset(mime='image/png'){
 const catalog=JSON.parse(await readFile('assets/free-assets/catalog.json','utf8'));
 const source=catalog.sources.find(source=>source.files.some(file=>file.mime===mime));
 const file=source.files.find(file=>file.mime===mime);
 return {
  id:'licensed-policy-fixture',mime:file.mime,data:(await readFile(file.file)).toString('base64'),rights:source.license,
  provenance:{origin:'third-party-free',sourceId:source.id,sourceFile:file.path,sourceHash:file.sha256,author:source.author,license:source.license,sourceUrl:source.sourceUrl,styleFamily:source.styleFamily},
 };
}
test('generated art and rights prose cannot authorize an unsourced production asset',()=>{
 assert.throws(()=>validateAssetPolicy({id:'generated',data:'YWk=',rights:'Original AI image, declared licensed'},{role:'visual',styleFamily:'painted'}),/E_ASSET_POLICY_PROVENANCE/);
});
test('a licensed raw asset is bound to its reviewed source bytes and style family',async()=>{
 const asset=await sourcedAsset(),styleFamily=asset.provenance.styleFamily;
 const receipt=validateAssetPolicy(asset,{role:'visual',styleFamily});
 assert.equal(receipt.sourceHash,asset.provenance.sourceHash);
 assert.equal(receipt.author,asset.provenance.author);
 assert.match(receipt.archiveHash,/^sha256:[a-f0-9]{64}$/);
 assert.throws(()=>validateAssetPolicy(asset,{role:'visual',styleFamily:'unrelated-art-style'}),/E_ASSET_POLICY_STYLE/);
 assert.throws(()=>validateAssetPolicy({...asset,data:Buffer.from('replacement generated bytes').toString('base64')},{role:'visual',styleFamily}),/E_ASSET_POLICY_BYTES/);
 for(const change of [
  provenance=>{provenance.sourceId='self-declared-source';},
  provenance=>{provenance.sourceFile='../generated.png';},
  provenance=>{provenance.author='Generated art';},
  provenance=>{provenance.license='CC0-1.0 invented declaration';},
  provenance=>{provenance.sourceUrl='https://unreviewed.invalid/art';},
  provenance=>{provenance.sourceHash='sha256:'+'0'.repeat(64);},
 ]){
  const modified=globalThis.structuredClone(asset);change(modified.provenance);
  assert.throws(()=>validateAssetPolicy(modified,{role:'visual',styleFamily}),/E_ASSET_POLICY_/);
 }
});

test('sourced PNG preparation removes color metadata and preserves encoded image data',async()=>{
 const original=await readFile('assets/kenney-harvest/source/tiny-farm/Tiles/tile_0008.png'),prepared=preparePngSource(original);
 const chunks=bytes=>{
  const result=[];
  for(let offset=8;offset<bytes.length;){
   const size=bytes.readUInt32BE(offset),kind=bytes.toString('ascii',offset+4,offset+8);
   result.push({kind,data:bytes.subarray(offset,offset+size+12).toString('base64')});
   offset+=size+12;
  }
  return result;
 };
 const originalChunks=chunks(original),preparedChunks=chunks(prepared);
 assert.ok(originalChunks.some(chunk=>chunk.kind==='gAMA'));
 assert.deepEqual(preparedChunks,originalChunks.filter(chunk=>!['gAMA','cHRM','iCCP','sRGB'].includes(chunk.kind)));
 assert.deepEqual(preparedChunks.filter(chunk=>chunk.kind==='IDAT'),originalChunks.filter(chunk=>chunk.kind==='IDAT'));
 assert.deepEqual(preparePngSource(prepared),prepared);
 assert.throws(()=>preparePngSource(original.subarray(0,original.length-1)),/E_ASSET_POLICY_PROCESSING/);
});

test('curated audio collections resolve seven distinct cues with analyzed source provenance',async()=>{
 const catalog=JSON.parse(await readFile('assets/free-assets/catalog.json','utf8'));
 assert.deepEqual(catalog.audioCollections.map(collection=>collection.id),['casual-warm','arcade-pop']);
 for(const collection of catalog.audioCollections){
  const hashes=new Set();
  for(const [role,id]of Object.entries(collection.cues)){
   const matches=catalog.sources.flatMap(source=>source.files.map(file=>({source,file}))).filter(({file})=>file.id===id);
   assert.equal(matches.length,1);const {source,file}=matches[0];
   assert.equal(file.audioMeta.role,role);assert.equal(file.audioMeta.auditionStatus,'analyzed');assert.equal(file.audioMeta.clipping,false);
   hashes.add(file.sha256);
   const asset={id,mime:file.mime,data:(await readFile(file.file)).toString('base64'),rights:source.license,provenance:{origin:'third-party-free',sourceId:source.id,sourceFile:file.path,sourceHash:file.sha256,author:source.author,license:source.license,sourceUrl:source.sourceUrl,styleFamily:source.styleFamily}};
   const receipt=validateAssetPolicy(asset,{role:'audio'});
   assert.equal(receipt.sourceHash,file.sha256);assert.equal(receipt.processing.kind,'audio-transcode');
  }
  assert.equal(hashes.size,7);
 }
});

test('sourced audio format conversion retains a separate licensed sound-pack identity',async()=>{
 const asset=await sourcedAsset('audio/wav');
 const receipt=validateAssetPolicy(asset,{role:'audio',styleFamily:'kenney-tiny-farm'});
 assert.equal(receipt.license,'CC0-1.0');
 assert.equal(receipt.processing.kind,'audio-transcode');
 assert.ok(['ffmpeg','Web Audio OfflineAudioContext'].includes(receipt.processing.tool));
 assert.match(receipt.processing.sourceSha256,/^sha256:[a-f0-9]{64}$/);
 assert.throws(()=>validateAssetPolicy(asset,{role:'visual',styleFamily:'kenney-tiny-farm'}),/E_ASSET_POLICY_STYLE|E_ASSET_POLICY_MEDIA/);
});
